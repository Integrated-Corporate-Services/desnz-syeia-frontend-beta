export const CRITICAL_ROUTES = [
  '/payment/callback',
  `${S37_BASE_URL}/:applicationId/payment-success`,
  `${S37_BASE_URL}/:applicationId/payment-failed`,
  '/admin/review-request/:requestId',
  '/admin/add-user',
];

export function isCriticalRoute(pathname: string): boolean {
  return CRITICAL_ROUTES.some(route => {
    const routePattern = route.replace(/:[\w]+/g, '[^/]+');
    const regex = new RegExp(`^${routePattern}$`);
    return regex.test(pathname);
  });
}
